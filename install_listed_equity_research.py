SKILL_NAME = 'listed-equity-research'


def check_payload(bundle):
    actual = hashlib.sha256(bundle).hexdigest()
    if actual != ARCHIVE_SHA256:
        raise ValueError('Installer data corrupted: archive SHA-256 mismatch')
    with zipfile.ZipFile(BytesIO(bundle)) as z:
        names = set(z.namelist())
        if f'{SKILL_NAME}/SKILL.md' not in names or f'{SKILL_NAME}/MANIFEST.json' not in names:
            raise ValueError('Not a complete skill ZIP')
        for i in z.infolist():
            name = i.filename
            parts = Path(name).parts
            if not parts or parts[0] != SKILL_NAME or '..' in parts or Path(name).is_absolute():
                raise ValueError(f'Unsafe path inside archive: {name}')
            if (i.external_attr >> 16) & 0o170000 == 0o120000:
                raise ValueError(f'Symlinks not supported: {name}')
        manifest = json.loads(z.read(f'{SKILL_NAME}/MANIFEST.json'))
        if manifest.get('name') != SKILL_NAME:
            raise ValueError('Incorrect manifest name')
        for file in manifest['files']:
            path = f'{SKILL_NAME}/{file["path"]}'
            content = z.read(path)
            if hashlib.sha256(content).hexdigest() != file['sha256'] or len(content) != file['bytes']:
                raise ValueError(f'File verification failed: {path}')
        return len(manifest['files'])


def install(root, run_test=False):
    archive = base64.b64decode(PAYLOAD_B64)
    count = check_payload(archive)
    root = Path(root).expanduser().resolve()
    root.mkdir(parents=True, exist_ok=True)
    dst = root / SKILL_NAME
    staging_dir = Path(tempfile.mkdtemp(prefix='.listed-equity-install-', dir=root))
    stage = staging_dir / SKILL_NAME
    backup = None
    try:
        with zipfile.ZipFile(BytesIO(archive)) as z:
            z.extractall(staging_dir)
        verify = subprocess.run([sys.executable, str(stage/'scripts'/'verify_install.py'), str(stage)],
                                capture_output=True, text=True, check=False)
        if verify.returncode:
            raise RuntimeError('File verification failed after extraction:\n' + verify.stdout + verify.stderr)
        if dst.exists():
            timestamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')
            backup = root / f'{SKILL_NAME}.backup.{timestamp}'
            idx = 1
            while backup.exists():
                backup = root / f'{SKILL_NAME}.backup.{timestamp}.{idx}'
                idx += 1
            dst.rename(backup)
        try:
            stage.rename(dst)
        except Exception:
            if backup and backup.exists() and not dst.exists():
                backup.rename(dst)
            raise
    finally:
        shutil.rmtree(staging_dir, ignore_errors=True)
    print('INSTALLED:', dst)
    print('VERIFIED:', count, 'files, SHA-256 OK')
    if backup:
        print('BACKUP:', backup)
    if run_test:
        result = subprocess.run([sys.executable, str(dst/'scripts'/'self_test.py')], cwd=dst, check=False)
        if result.returncode:
            print('WARNING: self_test failed (matplotlib may be missing). Installation integrity passed.')
            return 2
    print('NEXT: reopen your agent session if required, then invoke the listed-equity-research skill.')
    return 0


def main():
    p = argparse.ArgumentParser(description='Install complete listed-equity-research skill offline')
    p.add_argument('--root', required=True, help='Parent skills root directory, e.g. ~/.agents/skills')
    p.add_argument('--test', action='store_true', help='Optionally run self_test.py (needs matplotlib)')
    args = p.parse_args()
    try:
        return install(args.root, args.test)
    except Exception as e:
        print('INSTALL FAILED:', e, file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
